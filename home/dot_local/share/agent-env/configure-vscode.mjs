import { constants, accessSync, existsSync, lstatSync, mkdirSync, readFileSync, realpathSync,
  renameSync, statSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { homedir } from "node:os";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

// chezmoi deploys this file to ~/.local/share/agent-env and runs it from
// run_onchange_after_50-configure-vscode.sh.
const root = fileURLToPath(new URL("./", import.meta.url));
const generated = "# Generated by dotfiles agent-env/configure-vscode.mjs.";
const quote = (value) => "'" + value.replaceAll("'", "'\\''") + "'";
const isLink = (path) => {
  try { return lstatSync(path).isSymbolicLink(); } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  }
};

export function writeChanged(path, before, content, mode) {
  if (before === content) return;
  mkdirSync(dirname(path), { recursive: true });
  if (existsSync(path)) {
    if (readFileSync(path, "utf8") !== before) throw new Error(`${path} changed during configuration. Retry.`);
    let backup = path + ".before-dotfiles-agents";
    for (let count = 1; existsSync(backup); count++) backup = path + `.before-dotfiles-agents.${count}`;
    writeFileSync(backup, before, { flag: "wx", mode: 0o600 });
    console.log(`Backup: ${backup}`);
  }
  const temporary = path + `.dotfiles-${process.pid}`;
  writeFileSync(temporary, content, { flag: "wx", mode });
  renameSync(temporary, path);
}

// Tokenize JSONC so edits preserve unrelated settings, comments, and formatting.
export function parseSettings(text) {
  const pattern = /\s+|\/\/[^\r\n]*|\/\*[\s\S]*?\*\/|"(?:\\[\s\S]|[^"\\])*"|[{}\[\]:,]|[^{}\[\]:,\s/]+/y;
  const tokens = [];
  let offset = 0;
  while (offset < text.length) {
    pattern.lastIndex = offset;
    const match = pattern.exec(text);
    if (!match) throw new Error(`Invalid settings JSONC at offset ${offset}.`);
    const raw = match[0];
    if (!/^\s|^\/\//.test(raw) && !raw.startsWith("/*")) {
      tokens.push({ raw, start: offset, end: pattern.lastIndex });
    }
    offset = pattern.lastIndex;
  }
  const normalized = tokens.filter((token, index) =>
    token.raw !== "," || !["}", "]"].includes(tokens[index + 1]?.raw) ||
      ["{", "[", ",", ":"].includes(tokens[index - 1]?.raw)).map((token) => token.raw).join(" ");
  const data = JSON.parse(normalized);
  if (!data || Array.isArray(data) || typeof data !== "object") {
    throw new Error("VS Code settings must be a JSON object.");
  }
  const properties = new Map();
  let index = 1;
  while (index < tokens.length - 1) {
    const key = JSON.parse(tokens[index].raw);
    if (properties.has(key)) throw new Error(`Duplicate settings key: ${key}`);
    index += 2;
    const start = tokens[index].start;
    let depth = 0;
    do {
      const raw = tokens[index++].raw;
      if (["{", "["].includes(raw)) depth++;
      if (["}", "]"].includes(raw)) depth--;
    } while (depth > 0);
    properties.set(key, { start, end: tokens[index - 1].end });
    if (tokens[index]?.raw === ",") index++;
  }
  return { data, properties, tokens };
}

export function updateSettings(text, updates) {
  const { data, properties, tokens } = parseSettings(text);
  const newline = text.includes("\r\n") ? "\r\n" : "\n";
  const indent = text.match(/^[\t ]+(?=")/m)?.[0] || "    ";
  const format = (value) => JSON.stringify(value, null, indent).replaceAll("\n", newline + indent);
  const edits = [];
  const additions = [];
  for (const [key, value] of Object.entries(updates)) {
    if (JSON.stringify(data[key]) === JSON.stringify(value)) continue;
    const property = properties.get(key);
    if (property) edits.push({ ...property, content: format(value) });
    else additions.push(`${indent}${JSON.stringify(key)}: ${format(value)}`);
  }
  if (additions.length) {
    const close = tokens.at(-1).start;
    let prefix = newline;
    if (properties.size && tokens.at(-2).raw !== ",") {
      const last = [...properties.values()].at(-1);
      if (last.end === close) prefix = "," + prefix;
      else edits.push({ start: last.end, end: last.end, content: "," });
    }
    edits.push({ start: close, end: close, content: prefix + additions.join("," + newline) + newline });
  }
  for (const edit of edits.sort((a, b) => b.start - a.start)) {
    text = text.slice(0, edit.start) + edit.content + text.slice(edit.end);
  }
  parseSettings(text);
  return text;
}

export function misePython({ home, env = process.env }) {
  const args = ["which", "--tool", "python@latest", "python"];
  const options = { cwd: home, env: { ...env, MISE_OFFLINE: "1" }, encoding: "utf8", timeout: 10000 };
  let result = spawnSync("mise", args, options);
  if (result.error?.code === "ENOENT") {
    result = spawnSync(join(home, ".local/bin/mise"), args, options);
  }
  if (result.error?.code === "ENOENT") throw new Error("mise is not installed or is not on PATH.");
  const executable = result.stdout?.trim();
  if (result.status !== 0 || !executable || !isAbsolute(executable)) {
    throw new Error("Cannot resolve installed Python latest. Run mise install python@latest.");
  }
  try {
    accessSync(executable, constants.X_OK);
    if (!statSync(executable).isFile()) throw new Error("Not an executable file.");
  } catch {
    throw new Error("Python latest is not installed. Run mise install python@latest.");
  }
  return executable;
}

export function vscodePlan({ appRoot, home, config, data, insiders = false, settings, python = false, env }) {
  const version = JSON.parse(readFileSync(join(appRoot, "package.json"), "utf8")).version;
  const [major, minor] = version.split(".").map(Number);
  if (major !== 1 || !Number.isInteger(minor) || minor < 142) {
    throw new Error("This integration requires VS Code 1.142 or newer.");
  }
  const declarations = readFileSync(join(appRoot, "out/vs/workbench/workbench.desktop.main.js"), "utf8");
  for (const key of ["chat.tools.terminal.terminalProfile.", "terminal.integrated.agentHostProfile.",
    "chat.agentHost.copilot.runtimePath"]) {
    if (!declarations.includes(key)) throw new Error(`This editor does not expose ${key}; review its integration before configuring it.`);
  }
  const target = `${process.platform}-${process.arch}`;
  const runtime = ["node_modules.asar.unpacked", "node_modules"].map((directory) =>
    join(appRoot, directory, "@github", `copilot-sdk-${target}`, "prebuilds", target, "copilot-runtime"))
    .find((path) => {
      try { accessSync(path, constants.X_OK); return statSync(path).isFile(); } catch { return false; }
    });
  if (!runtime) throw new Error("Cannot find this VS Code installation's bundled Copilot runtime.");
  const product = insiders ? "Code - Insiders" : "Code";
  settings ||= join(config, product, "User/settings.json");
  if (isLink(settings)) {
    throw new Error("Settings are symlinked. Update the owning configuration instead.");
  }
  const before = existsSync(settings) ? readFileSync(settings, "utf8") : "{}\n";
  const { data: current } = parseSettings(before);
  const shell = join(root, "bin/bash");
  accessSync(shell, constants.X_OK);
  const shellSetting = shell.startsWith(home + "/") ? "${env:HOME}" + shell.slice(home.length) : shell;
  const launcher = join(data, "dotfiles/vscode", insiders ? "insiders" : "stable", "copilot-runtime");
  const updates = {
    [`chat.tools.terminal.terminalProfile.${process.platform === "darwin" ? "osx" : "linux"}`]: { path: shellSetting },
    [`terminal.integrated.agentHostProfile.${process.platform === "darwin" ? "osx" : "linux"}`]: { path: shellSetting },
    "chat.agentHost.copilot.runtimePath": launcher,
  };
  if (python) updates["python.defaultInterpreterPath"] = misePython({ home, env });
  // Values written by this script, or by the pre-chezmoi layout, may be replaced.
  const replaceable = {
    "python.defaultInterpreterPath": (value) => typeof value === "string" &&
      (["python", "python3", "/bin/python", "/bin/python3", "/usr/bin/python", "/usr/bin/python3"].includes(value) ||
        /\/mise\/installs\/python\/[^/]+\/bin\/python3?$/.test(value)),
    "chat.agentHost.copilot.runtimePath": () => false,
  };
  for (const [key, desired] of Object.entries(updates)) {
    const ours = replaceable[key] ?? ((value) => /\/agents\/bash$/.test(value?.path ?? ""));
    if (ours(current[key])) continue;
    if (current[key] != null && JSON.stringify(current[key]) !== JSON.stringify(desired)) {
      throw new Error(`Existing ${key} differs. Review it before replacing it.`);
    }
  }
  const content = `#!/bin/bash\n${generated}\nexec ${quote(join(root, "node-lts"))} ${quote(join(root, "command-launcher.mjs"))} ${quote(runtime)} "$@"\n`;
  if (isLink(launcher) || existsSync(launcher) &&
      !readFileSync(launcher, "utf8").startsWith("#!/bin/bash\n# Generated by dotfiles")) {
    throw new Error("The runtime launcher is not managed by dotfiles; refusing to replace it.");
  }
  return { settings, before, after: updateSettings(before, updates), launcher, content, runtime, updates };
}

function findAppRoot(insiders) {
  const command = insiders ? "code-insiders" : "code";
  for (const directory of (process.env.PATH || "").split(":")) {
    const path = join(directory, command);
    try {
      accessSync(path, constants.X_OK);
      const bin = dirname(realpathSync(path));
      for (const app of [resolve(bin, "../resources/app"), resolve(bin, "..")]) {
        if (existsSync(join(app, "package.json"))) return app;
      }
    } catch { /* Try the next PATH entry. */ }
  }
  throw new Error(`Cannot locate ${command}. Use --app-root with its resources/app directory.`);
}

export function main(args = process.argv.slice(2)) {
  const { values } = parseArgs({ args, options: {
    insiders: { type: "boolean" }, "dry-run": { type: "boolean" }, help: { type: "boolean" },
    "app-root": { type: "string" }, settings: { type: "string" }, python: { type: "boolean" },
  } });
  if (values.help) {
    console.log("Usage: node ~/.local/share/agent-env/configure-vscode.mjs [--insiders] [--python] [--dry-run] [--app-root PATH] [--settings PATH]");
    console.log("--python also sets the default Python interpreter to mise's installed Python latest. Saved workspace selections are unchanged.");
    return;
  }
  if (!["linux", "darwin"].includes(process.platform)) throw new Error("Use this integration on Linux, WSL, or macOS.");
  const home = process.env.HOME || homedir();
  const plan = vscodePlan({ home, insiders: values.insiders, python: values.python,
    appRoot: resolve(values["app-root"] || findAppRoot(values.insiders)),
    settings: values.settings && resolve(values.settings),
    config: process.platform === "darwin" ? join(home, "Library/Application Support") :
      process.env.XDG_CONFIG_HOME || join(home, ".config"),
    data: process.env.XDG_DATA_HOME || join(home, ".local/share"),
  });
  console.log(`Settings: ${plan.settings}`);
  console.log(`Bundled runtime: ${plan.runtime}`);
  console.log(JSON.stringify(plan.updates, null, 2));
  if (values["dry-run"]) return;
  const check = spawnSync(join(root, "node-lts"), [join(root, "command-launcher.mjs"), "/bin/sh", "-c", ":"],
    { cwd: home, encoding: "utf8" });
  if (check.status !== 0) throw new Error(check.stderr.trim() || "Cannot start the shared agent launcher.");
  const previous = existsSync(plan.launcher) ? readFileSync(plan.launcher, "utf8") : undefined;
  writeChanged(plan.launcher, previous, plan.content, 0o755);
  const mode = existsSync(plan.settings) ? statSync(plan.settings).mode & 0o777 : 0o600;
  writeChanged(plan.settings, existsSync(plan.settings) ? plan.before : undefined, plan.after, mode);
  console.log("Agent environments configured. Restart VS Code and create fresh agent terminals/sessions.");
  if (values.python) console.log("Python default configured. Saved workspace selections are unchanged; use Python: Select Interpreter to change an existing workspace.");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(); } catch (error) { console.error(`VS Code setup: ${error.message}`); process.exit(1); }
}
